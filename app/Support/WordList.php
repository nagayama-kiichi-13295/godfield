    public static function forMatch(string $matchId, int $count = 40): array
    {
        $words = self::WORDS;
        $seed = crc32($matchId);

        for ($i = count($words) - 1; $i > 0; $i--) {
            $seed = ($seed * 1103515245 + 12345) & 0x7fffffff;
            $j = $seed % ($i + 1);
            [$words[$i], $words[$j]] = [$words[$j], $words[$i]];
        }

        return array_map(
            fn ($w) => ['d' => $w[0], 'k' => $w[1]],
            array_slice($words, 0, min($count, count($words)))
        );
    }
